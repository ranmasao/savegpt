/**
 * Backend payload -> the normalized Conversation of PLAN.md section 3.
 *
 * Pure: no DOM, no chrome APIs, no network. It runs under Node against saved
 * payloads, which is the only way this logic gets tested - the content script
 * loads it dynamically so tests and production share one implementation.
 */

/** Roles kept as conversation content. */
const KEPT_ROLES = new Set(['user', 'assistant']);

/** Reasoning content, dropped in v0.1 and declared in the front matter. */
const REASONING_TYPES = new Set(['thoughts', 'reasoning_recap']);

/** Tool plumbing, dropped in v0.1 and declared in the front matter. */
const TOOL_TYPES = new Set([
  'code',
  'execution_output',
  'tether_browsing_display',
  'tether_quote',
]);

/**
 * The mapping is a tree: edits and regenerations create sibling branches.
 * Walking parent pointers back from `current_node` yields exactly the branch
 * the user is looking at, and nothing else.
 */
export function branchFromMapping(payload) {
  const mapping = payload.mapping || {};
  const chain = [];
  const seen = new Set();
  let nodeId = payload.current_node;

  while (nodeId && mapping[nodeId] && !seen.has(nodeId)) {
    seen.add(nodeId);
    chain.push(mapping[nodeId]);
    nodeId = mapping[nodeId].parent;
  }
  return chain.reverse();
}

/**
 * An image generated by the assistant arrives as a `tool` message carrying a
 * `multimodal_text` image pointer. It is not tool plumbing - it is the visible
 * answer to the user's prompt. Dropping it leaves two consecutive user turns
 * with nothing between them, and an export that ends on an unanswered prompt.
 */
export function isGeneratedImageMessage(message) {
  if (!message || !message.author || message.author.role !== 'tool') return false;
  if (!message.content || message.content.content_type !== 'multimodal_text') return false;
  return (message.content.parts || []).some(
    (part) => part && part.content_type === 'image_asset_pointer'
  );
}

/**
 * ChatGPT marks up web-search citations and entity chips inline using private-use
 * codepoints its own renderer understands (U+E200..U+E2FF, wrapping text such as
 * `cite` and `turn0search7`). Left alone they come out as literal garbage -
 * "citeturn0search7turn0search19" - and the URLs behind them, which live in
 * `metadata.content_references`, are lost entirely.
 *
 * Each reference carries an `alt` that is already the Markdown to use, so the
 * repair is a substitution of a span the payload itself delimits.
 */
const MARKER_CODEPOINTS = /[\uE200-\uE2FF]/g;

function firstString(...candidates) {
  for (const candidate of candidates) {
    if (typeof candidate === 'string' && candidate !== '') return candidate;
  }
  return '';
}

export function resolveReferences(text, references) {
  let resolved = 0;
  let output = text;

  if (Array.isArray(references) && references.length > 0) {
    const edits = [];

    for (const ref of references) {
      const matched = ref && ref.matched_text;
      if (typeof matched !== 'string' || matched === '') continue;

      const replacement = firstString(ref.alt, ref.prompt_text, ref.name);

      // `sources_footnote` matches a bare space and replaces it with nothing.
      // Honouring that deletes a real word separator, so never let a reference
      // consume plain whitespace.
      if (replacement === '' && matched.trim() === '') continue;
      const start = Number.isInteger(ref.start_idx) ? ref.start_idx : -1;

      if (start >= 0 && text.slice(start, start + matched.length) === matched) {
        edits.push({ start, end: start + matched.length, replacement });
      } else {
        const found = text.indexOf(matched);
        if (found >= 0) edits.push({ start: found, end: found + matched.length, replacement });
      }
    }

    // Apply right to left so earlier offsets stay valid, skipping overlaps.
    edits.sort((a, b) => b.start - a.start);
    let boundary = Infinity;
    for (const edit of edits) {
      if (edit.end > boundary) continue;
      output = output.slice(0, edit.start) + edit.replacement + output.slice(edit.end);
      boundary = edit.start;
      resolved += 1;
    }
  }

  // Anything the references did not account for would still render as garbage.
  const leftovers = output.match(MARKER_CODEPOINTS);
  if (leftovers) output = output.replace(MARKER_CODEPOINTS, '');

  return { text: output, resolved, stripped: leftovers ? leftovers.length : 0 };
}

function imageAltText(entry, fallback) {
  const dallePrompt = entry.metadata && entry.metadata.dalle && entry.metadata.dalle.prompt;
  for (const candidate of [entry.alt, entry.text, dallePrompt, fallback]) {
    if (typeof candidate === 'string' && candidate.trim() !== '') return candidate.trim();
  }
  return '';
}

function partsFromContent(content, omissions, title, references, tally) {
  const type = content && content.content_type;
  const parts = [];

  if (!content) return parts;

  if (REASONING_TYPES.has(type)) {
    omissions.thoughts = true;
    return parts;
  }
  if (TOOL_TYPES.has(type)) {
    omissions.tools = true;
    return parts;
  }

  if (type === 'text') {
    for (const text of content.parts || []) {
      if (typeof text !== 'string' || text.trim() === '') continue;

      const cleaned = resolveReferences(text, references);
      tally.resolved += cleaned.resolved;
      tally.stripped += cleaned.stripped;
      parts.push({ kind: 'markdown', text: cleaned.text });
    }
    return parts;
  }

  if (type === 'multimodal_text') {
    for (const entry of content.parts || []) {
      if (typeof entry === 'string') {
        if (entry.trim() !== '') parts.push({ kind: 'markdown', text: entry });
      } else if (entry && typeof entry === 'object') {
        parts.push({ kind: 'image', text: imageAltText(entry, title) });
      }
    }
    return parts;
  }

  // Unknown shape: keep it rather than drop it, so a backend change degrades
  // visibly instead of silently losing text.
  parts.push({
    kind: 'unknown',
    text: JSON.stringify(content, null, 2),
    language: 'json',
    contentType: type || 'undefined',
  });
  return parts;
}

/** Distinct model slugs, in order of first appearance. */
function modelsUsed(messages) {
  const seen = [];
  for (const message of messages) {
    if (message.model && !seen.includes(message.model)) seen.push(message.model);
  }
  return seen;
}

/**
 * @param {object} payload the `/backend-api/conversation/<id>` response
 * @param {object} [options] `{ conversationId, origin }`
 * @returns {object} Conversation
 */
export function conversationFromPayload(payload, options = {}) {
  const conversationId = options.conversationId || payload.conversation_id || '';
  const origin = options.origin || 'https://chatgpt.com';
  const omissions = { tools: false, thoughts: false };
  const citations = { resolved: 0, stripped: 0 };
  const messages = [];

  for (const node of branchFromMapping(payload)) {
    const message = node.message;
    if (!message) continue;

    const role = message.author && message.author.role;
    const metadata = message.metadata || {};

    if (metadata.is_visually_hidden_from_conversation) continue;
    if (role === 'system') continue;

    const generatedImage = isGeneratedImageMessage(message);
    if (!KEPT_ROLES.has(role) && !generatedImage) {
      omissions.tools = true;
      continue;
    }

    const tally = { resolved: 0, stripped: 0 };
    const parts = partsFromContent(
      message.content,
      omissions,
      metadata.image_gen_title,
      metadata.content_references,
      tally
    );
    if (parts.length === 0) continue;

    citations.resolved += tally.resolved;
    citations.stripped += tally.stripped;

    messages.push({
      id: message.id || node.id,
      // A generated image is the assistant speaking, whatever carried it.
      role: generatedImage ? 'assistant' : role,
      createTime: typeof message.create_time === 'number' ? message.create_time : null,
      model: metadata.model_slug || null,
      citations: tally.resolved || null,
      parts,
    });
  }

  return {
    id: conversationId,
    title: payload.title || '',
    url: `${origin}/c/${conversationId}`,
    createTime: typeof payload.create_time === 'number' ? payload.create_time : null,
    updateTime: typeof payload.update_time === 'number' ? payload.update_time : null,
    models: modelsUsed(messages),
    source: 'api',
    omissions,
    citations,
    messages,
  };
}
